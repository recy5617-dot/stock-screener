DT_LIMIT_PENALTY = 10            # 並從總分扣這麼多分（開盤常直接跳空、不好進場，設0=只提醒不扣分）

# ---- 權重（總和100）----
DT_WEIGHT_VOLATILITY = 25        # A 波動度
DT_WEIGHT_LIQUIDITY = 20         # B 流動性
DT_WEIGHT_VOLUME = 20            # C 量能放大
DT_WEIGHT_CLOSE = 15             # D 收盤強弱（與方向一致）
DT_WEIGHT_TREND = 10             # E 順勢（均線排列 / 突破20日高低點）
DT_WEIGHT_CHIPS = 10             # F 法人同向（外資或投信買超=偏多，賣超=偏空）

# ---- 輸出 ----
