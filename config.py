# -*- coding: utf-8 -*-
"""
選股系統全域設定
================
所有可調參數集中在這裡，方便日後微調而不用動到邏輯程式碼。
"""

import os

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(BASE_DIR, "cache", "market_data.sqlite3")
OUTPUT_DIR = os.path.join(BASE_DIR, "output")
DOCS_DIR = os.path.join(BASE_DIR, "docs")  # GitHub Pages 網頁報表輸出位置

# 抓取歷史資料的天數（要足夠計算 MA20 / KD(9,3,3) / 20日高點，
# 抓多一點比較保險，遇到假日、缺資料也不怕）
BACKFILL_TRADING_DAYS = 70

# 對外部 TWSE / TPEX 網站的請求延遲秒數（避免被判定為異常流量而封鎖）
REQUEST_DELAY_SEC = 0.35
REQUEST_TIMEOUT_SEC = 15
REQUEST_RETRY = 3

# ---------------------------------------------------------------
# ① 月線 (MA20)
# ---------------------------------------------------------------
MA_PERIOD = 20
MA_SLOPE_LOOKBACK = 5          # 判斷月線走平/向上：跟 5 個交易日前的 MA20 比
MA_JUST_RECLAIMED_LOOKBACK = 3  # 「剛站回月線」的判斷範圍（近 N 日內曾跌破）

# ---------------------------------------------------------------
# ② KD 指標
# ---------------------------------------------------------------
KD_RSV_PERIOD = 9
KD_K_SMOOTH = 3
KD_D_SMOOTH = 3
KD_HIGH_ZONE = 80              # 高檔鈍化的門檻
KD_STAGNANT_DAYS = 8            # 連續幾天 K>KD_HIGH_ZONE 視為「高檔鈍化已久」

# ---------------------------------------------------------------
# ③ 三大法人籌碼
# ---------------------------------------------------------------
TRUST_CONSEC_BUY_DAYS = 2       # 投信「連買」至少要幾天

# ---------------------------------------------------------------
# ④ 融資
# ---------------------------------------------------------------
# 股價上漲時，融資餘額較前一日增加超過這個比例 -> 視為「暴增」(危險訊號)
MARGIN_SURGE_THRESHOLD = 0.03    # 3%
# 融資餘額較前一日「持平或下降」-> 額外加分
MARGIN_FLAT_OR_DOWN_BONUS = True

# ---------------------------------------------------------------
# ⑤ 突破 / 量能
# ---------------------------------------------------------------
BREAKOUT_LOOKBACK = 20          # 判斷「前高/整理區」用的回顧天數
VOLUME_AVG_DAYS = 5              # 均量比較基準（近 N 日均量，不含當日）
VOLUME_SURGE_RATIO = 1.5         # 當日量 需 > 均量 * 此倍數 才算「放量」
LONG_UPPER_SHADOW_RATIO = 0.35   # (高-收)/(高-低) 超過此比例 視為長上影線（扣分）

# ---------------------------------------------------------------
# 權重（月線方向 ＞ 籌碼 ＞ 成交量 ＞ KD；融資是風險濾網不是加分項）
# ---------------------------------------------------------------
WEIGHT_MA20 = 35
WEIGHT_CHIPS = 30
WEIGHT_VOLUME = 20
WEIGHT_KD = 15
# 融資：不列入加權分數，而是「警示 / 扣分」濾網
MARGIN_PENALTY_POINTS = 15       # 融資暴增時，從總分扣的分數

# ---------------------------------------------------------------
# 篩選市場：TWSE=上市, TPEX=上櫃
# TWSE 的三個資料來源已在開發時實際測試成功可用。
# TPEX 的端點是依官方慣用格式撰寫，但開發環境對 tpex.org.tw 有網路封鎖、
# 無法實際跑一次驗證欄位是否正確，正式使用前請先執行 `python main.py --test-tpex`
# 確認資料抓得到、欄位對得上，再把 "TPEX" 加回下面這行。詳見 fetch_tpex.py 開頭說明。
# ---------------------------------------------------------------
MARKETS = ["TWSE"]  # 驗證過 TPEX 後可改成 ["TWSE", "TPEX"]

# 排除的股票代碼前綴（ETF、權證等雜訊可依需要調整；預設不排除）
EXCLUDE_CODE_PREFIXES = []  # 例如 ["00"] 可排除大部分 ETF

os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
os.makedirs(OUTPUT_DIR, exist_ok=True)
os.makedirs(DOCS_DIR, exist_ok=True)
