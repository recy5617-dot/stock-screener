# ---------------------------------------------------------------
MARKETS = ["TWSE"]  # 驗證過 TPEX 後可改成 ["TWSE", "TPEX"]

# 排除的股票代碼前綴（ETF、權證等雜訊可依需要調整；預設不排除）
EXCLUDE_CODE_PREFIXES = []  # 例如 ["00"] 可排除大部分 ETF

# ===============================================================
# ⚡ 當沖候選名單（daytrade.py）—— 跟上面的波段選股是兩套獨立邏輯
# ===============================================================
# 用「今天收盤後」的日K資料，挑出「明天」適合當沖觀察的股票。
# 當沖要的不是「會不會漲」，而是：流動性夠(進出不卡) + 波動夠大(有價差可賺) + 有人氣(量能放大)
# + 方向明確(收盤強/弱、順勢)。所以條件跟權重與波段選股完全不同。

# ---- 硬性濾網（不符合直接不列入，不算分）----
DT_MIN_VOLUME_LOTS = 3000        # 當天成交量至少幾張（當沖對流動性要求比波段高很多）
DT_MIN_TURNOVER = 3e8            # 當天成交值(元)至少多少，預設3億，避免低價股靠張數灌量
DT_MIN_PRICE = 10                # 股價下限（太低價跳動一檔的比例太大、成本占比高）
DT_MAX_PRICE = 1000              # 股價上限（太高價一張資金需求太大，可依自己資金調整）
DT_EXCLUDE_ETF = True            # 排除代號 00 開頭的 ETF / 債券型商品（波動小，不適合當沖）

# ---- A 波動度：ATR%（近N日平均真實波幅 / 收盤價）----
DT_ATR_PERIOD = 14
DT_ATR_PCT_MIN = 2.5             # 低於這個波動，扣掉手續費+證交稅(當沖減半)後價差太小
DT_ATR_PCT_MAX = 8.0             # 高於這個波動太野，停損容易被掃（仍會列入但降分）

# ---- B 流動性：成交值 ----
DT_TURNOVER_FULL_SCORE = 3e9     # 成交值達到 30億 給滿分（介於門檻與此值之間依對數比例給分）

# ---- C 量能放大：今日量 / 近5日均量（不含今日）----
DT_VOLUME_RATIO_MIN = 1.5        # 至少放大幾倍才算「有人氣」
DT_VOLUME_RATIO_FULL = 2.5       # 放大到幾倍給滿分

# ---- D 收盤位置：(收盤-最低)/(最高-最低) ----
DT_CLOSE_POS_STRONG = 0.7        # 做多：收在當日振幅上緣30%內；做空：收在下緣30%內（1-0.7）

# ---- 漲跌停提醒 ----
